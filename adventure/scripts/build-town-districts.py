def part_image(source: Image.Image, part: dict, masks: dict, output: Path) -> None:
    x, y = part["localAnchor"]["x"], part["localAnchor"]["y"]
    width, height = part["width"], part["height"]
    mask = Image.new("L", source.size, 0)
    draw = ImageDraw.Draw(mask)
    for polygon in masks.get("include", []):
        draw.polygon(polygon, fill=255)
    for rect in masks.get("includeRects", []):
        draw.rectangle(rect, fill=255)
    for polygon in masks.get("holes", []):
        draw.polygon(polygon, fill=0)
    for polygon in masks.get("holesLocal", []):
        draw.polygon([(x + px, y + py) for px, py in polygon], fill=0)
    crop = source.crop((x, y, x + width, y + height)).copy()
    alpha = ImageChops.multiply(crop.getchannel("A"), mask.crop((x, y, x + width, y + height)))
    crop.putalpha(alpha)
    if alpha.getbbox() is None:
        raise ValueError(f"Empty cutout: {part['id']}")
    # These overlays are copied pixels, never redrawn art.
    crop.save(output, format="PNG", optimize=True)


def build() -> None:
    config = json.loads(MANIFEST.read_text())
    OUTPUT.mkdir(parents=True, exist_ok=True)
    for group_id, filename in SOURCES.items():
        source = Image.open(ASSETS / filename).convert("RGBA")
        group = config["groups"][group_id]
        expected = (group["nativeSize"]["width"], group["nativeSize"]["height"])
        if source.size != expected:
            raise ValueError(f"{group_id}: expected {expected}, got {source.size}")
        group_dir = OUTPUT / group_id
        group_dir.mkdir(parents=True, exist_ok=True)
        base = source.copy()
        for opening in group.get("baseOpenings", []):
            # Clear the approved front wall only; the map's ground remains visible through the entrance.
            alpha = base.getchannel("A")
            ImageDraw.Draw(alpha).rectangle((opening["x"], opening["y"], opening["x"] + opening["width"] - 1, opening["y"] + opening["height"] - 1), fill=0)
            base.putalpha(alpha)
        base.save(group_dir / "base.png", format="PNG", optimize=True)
        for part in group["parts"]:
            masks = MASKS.get(part["id"])
            if masks is None:
                raise ValueError(f"Missing cutout mask: {part['id']}")
            part_image(source, part, masks, group_dir / Path(part["url"]).name)

        if group_id == "arcade-nook":
            opening = group["baseOpenings"][0]
            crop = base.getchannel("A").crop((opening["x"], opening["y"], opening["x"] + opening["width"], opening["y"] + opening["height"]))
            if crop.getbbox() is not None:
                raise AssertionError("Arcade entrance is not transparent")

        # Validate every interactive photo window is transparent in its frame cutout.
        for part in group["parts"]:
            if "photoQuad" not in part:
                continue
            cutout = Image.open(group_dir / Path(part["url"]).name).convert("RGBA")
            window = Image.new("L", cutout.size, 0)
            points = [(p["x"], p["y"]) for p in part["photoQuad"]]
            ImageDraw.Draw(window).polygon(points, fill=255)
            if ImageChops.multiply(cutout.getchannel("A"), window).getbbox() is not None:
                raise AssertionError(f"Photo window must be transparent: {part['id']}")

    print(f"Exported three layered districts under {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    build()
